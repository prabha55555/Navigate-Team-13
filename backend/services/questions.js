/**
 * Validation and normalisation of question input shared by assessments and
 * the question bank. Answer keys given as option letters ("B") or indexes (1)
 * are stored as option text, which is what students submit.
 */
const { normalizeQuestionType } = require('./gradingService');
const { badRequest } = require('../utils/errors');

const QUESTION_TYPES = ['multiple-choice', 'multiple-select', 'true-false', 'short-answer', 'essay'];
const DIFFICULTIES = ['Easy', 'Medium', 'Hard'];
// Question ids become keys of Submission.answers, so keep them free of '.' and '$'.
const QUESTION_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;
const MAX_OPTIONS = 10;

const isBlank = (v) => v === undefined || v === null || (typeof v === 'string' && v.trim() === '')
  || (Array.isArray(v) && v.length === 0);

function normalizeDifficulty(value) {
  const v = String(value || '').trim().toLowerCase();
  if (v === 'easy') return 'Easy';
  if (v === 'hard') return 'Hard';
  return 'Medium';
}

/** Option text for a key given as text, a letter or an index; undefined when it matches nothing. */
function resolveOption(value, options) {
  if (isBlank(value)) return undefined;
  const text = String(value).trim();
  const exact = options.find((o) => o.toLowerCase() === text.toLowerCase());
  if (exact !== undefined) return exact;
  if (/^[A-Ja-j]$/.test(text)) return options[text.toUpperCase().charCodeAt(0) - 65];
  if (typeof value === 'number' || /^\d+$/.test(text)) return options[Number(text)];
  return undefined;
}

function toTrueFalse(value) {
  const v = String(value).trim().toLowerCase();
  if (v === 'true' || v === 't') return 'True';
  if (v === 'false' || v === 'f') return 'False';
  return null;
}

/**
 * Validates one question and returns its canonical plain form.
 * @param {object} raw question as sent by a client (or generated by AI)
 * @param {number} index position, for error messages
 */
function cleanQuestion(raw, index = 0) {
  const label = `Question ${index + 1}`;
  if (!raw || typeof raw !== 'object') throw badRequest(`${label} is invalid`, { field: `questions.${index}` });
  const type = normalizeQuestionType(raw.type || raw.questionType);
  if (!QUESTION_TYPES.includes(type)) {
    throw badRequest(`${label} has an unsupported type`, { field: `questions.${index}.type`, allowed: QUESTION_TYPES });
  }
  const text = String(raw.text || raw.question || '').trim();
  if (!text) throw badRequest(`${label} needs question text`, { field: `questions.${index}.text` });

  let options = [];
  if (type === 'true-false') options = ['True', 'False'];
  else if (type === 'multiple-choice' || type === 'multiple-select') {
    options = (Array.isArray(raw.options) ? raw.options : [])
      .map((o) => String(o === null || o === undefined ? '' : o).trim())
      .filter(Boolean)
      .slice(0, MAX_OPTIONS);
  }

  let correctAnswer = null;
  const key = raw.correctAnswer;
  if (type === 'multiple-choice') correctAnswer = resolveOption(key, options) ?? null;
  else if (type === 'multiple-select') {
    const keys = (Array.isArray(key) ? key : (isBlank(key) ? [] : [key]))
      .map((k) => resolveOption(k, options))
      .filter((k) => k !== undefined);
    correctAnswer = keys.length ? [...new Set(keys)] : null;
  } else if (type === 'true-false') correctAnswer = isBlank(key) ? null : toTrueFalse(key);
  else if (type === 'short-answer') {
    const accepted = (Array.isArray(key) ? key : [key]).filter((k) => !isBlank(k) && typeof k !== 'object')
      .map((k) => String(k).trim().slice(0, 2000));
    correctAnswer = accepted.length > 1 ? accepted : (accepted[0] || null);
  } else if (!isBlank(key)) correctAnswer = String(key).trim().slice(0, 5000);

  const points = Number(raw.points);
  const question = {
    type,
    text: text.slice(0, 10000),
    options,
    correctAnswer,
    points: Number.isFinite(points) && points >= 0 ? Math.min(points, 1000) : 1,
    topic: String(raw.topic || '').trim().slice(0, 120),
    difficulty: normalizeDifficulty(raw.difficulty),
    bloomLevel: String(raw.bloomLevel || '').trim().slice(0, 40),
    explanation: String(raw.explanation || '').trim().slice(0, 5000)
  };
  const id = raw.id === undefined || raw.id === null ? '' : String(raw.id);
  if (QUESTION_ID_PATTERN.test(id)) question.id = id;
  return question;
}

/** Validates a question list; ids are kept when valid and unique, otherwise reassigned. */
function cleanQuestions(list) {
  if (!Array.isArray(list)) throw badRequest('questions must be a list', { field: 'questions' });
  if (list.length > 500) throw badRequest('An assessment can have at most 500 questions', { field: 'questions' });
  const seen = new Set();
  const cleaned = list.map((q, i) => cleanQuestion(q, i));
  cleaned.forEach((q) => {
    if (q.id && !seen.has(q.id)) seen.add(q.id);
    else delete q.id;
  });
  let n = 1;
  cleaned.forEach((q) => {
    if (q.id) return;
    while (seen.has(`q${n}`)) n += 1;
    q.id = `q${n}`;
    seen.add(q.id);
  });
  return cleaned;
}

/** Objective questions (choice / true-false) must have a key that matches their options. */
function hasValidKey(q) {
  if (q.type === 'multiple-choice') return !isBlank(q.correctAnswer) && q.options.includes(q.correctAnswer);
  if (q.type === 'multiple-select') {
    return Array.isArray(q.correctAnswer) && q.correctAnswer.length > 0 && q.correctAnswer.every((k) => q.options.includes(k));
  }
  if (q.type === 'true-false') return q.correctAnswer === 'True' || q.correctAnswer === 'False';
  return true;
}

module.exports = {
  QUESTION_TYPES, DIFFICULTIES, QUESTION_ID_PATTERN, normalizeDifficulty, cleanQuestion, cleanQuestions, hasValidKey
};
